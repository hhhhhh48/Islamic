window.applyHalalI18n = function(){
  var lang = localStorage.getItem('lang') || 'ar';
  if(lang !== 'ar' && lang !== 'en') lang = 'en';
  var t = window.HALAL_I18N[lang];
  var rtl = lang === 'ar';
  document.documentElement.lang = lang;
  document.documentElement.dir = rtl ? 'rtl' : 'ltr';
  document.querySelectorAll('[data-hi18n]').forEach(function(el){
    var k = el.getAttribute('data-hi18n');
    if(t[k]) el.innerHTML = t[k];
  });
}

