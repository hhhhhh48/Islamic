// ═══ Apply function ═══
window.applyRemI18n = function(){
  var lang = localStorage.getItem('lang') || 'ar';
  var t = window.REM_I18N[lang] || window.REM_I18N.ar;
  var rtl = ['ar','ur','fa','ku','ps','he'].indexOf(lang) !== -1;
  document.documentElement.lang = lang;
  document.documentElement.dir = rtl ? 'rtl' : 'ltr';
  document.querySelectorAll('[data-ri18n]').forEach(function(el){
    var k = el.getAttribute('data-ri18n');
    if(t[k]) el.textContent = t[k];
  });
  document.querySelectorAll('[data-ri18n-ph]').forEach(function(el){
    var k = el.getAttribute('data-ri18n-ph');
    if(t[k]) el.placeholder = t[k];
  });
};

// ═══ Switcher ═══
window.injectRemSwitcher = function(){
  if(document.getElementById('remLangSelect')) return;
  var bar = document.querySelector('.lang-bar');
  if(!bar) return;
  var langs = {ar:'🇸🇦 العربية',en:'🇬🇧 English',fr:'🇫🇷 Français',es:'🇪🇸 Español',de:'🇩🇪 Deutsch',tr:'🇹🇷 Türkçe',ur:'🇵🇰 اردو',id:'🇮🇩 Indonesia',ru:'🇷🇺 Русский',zh:'🇨🇳 中文'};
  var sel = document.createElement('select');
  sel.id = 'remLangSelect';
  sel.className = 'lang-select';
  Object.keys(langs).forEach(function(c){
    var o = document.createElement('option');
    o.value = c; o.textContent = langs[c];
    sel.appendChild(o);
  });
  sel.value = localStorage.getItem('lang') || 'ar';
  sel.addEventListener('change', function(){
    localStorage.setItem('lang', this.value);
    window.applyRemI18n();
  });
  var firstA = bar.querySelector('a');
  if(firstA) bar.insertBefore(sel, firstA);
  else bar.appendChild(sel);
};

document.addEventListener('DOMContentLoaded', function(){
  window.injectRemSwitcher();
  window.applyRemI18n();
});
