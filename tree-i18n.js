window.applyTreeI18n = function(){
  var lang = localStorage.getItem('lang') || 'ar';
  var t = window.TREE_I18N[lang] || window.TREE_I18N.ar;
  var rtl = ['ar','ur','fa','ku','ps','he'].indexOf(lang) !== -1;
  document.documentElement.lang = lang;
  document.documentElement.dir = rtl ? 'rtl' : 'ltr';
  document.querySelectorAll('[data-ti18n]').forEach(function(el){
    var k = el.getAttribute('data-ti18n');
    if(t[k]) el.textContent = t[k];
  });
  // Update deeds dynamically
  if(window.__renderDeeds){
    window.__renderDeeds();
  }
};

