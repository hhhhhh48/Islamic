// Apply function
window.applyCardsI18n = function(){
  var lang = localStorage.getItem('lang') || 'ar';
  var t = window.CARDS_I18N[lang] || window.CARDS_I18N.ar;
  var rtl = ['ar','ur','fa','ku','ps','he'].indexOf(lang) !== -1;
  document.documentElement.lang = lang;
  document.documentElement.dir = rtl ? 'rtl' : 'ltr';

  document.querySelectorAll('[data-ci18n]').forEach(function(el){
    var k = el.getAttribute('data-ci18n');
    if(t[k]) el.textContent = t[k];
  });
  document.querySelectorAll('[data-ci18n-ph]').forEach(function(el){
    var k = el.getAttribute('data-ci18n-ph');
    if(t[k]) el.placeholder = t[k];
  });

  // Bismillah on card
  var bis = document.querySelector('.card-bismillah');
  if(bis && t.bismillah) bis.textContent = t.bismillah;
};
