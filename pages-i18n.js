// ═══ Auto-apply function ═══
window.PAGES_I18N.apply = function(){
  var lang = localStorage.getItem('lang') || 'ar';
  var t = window.PAGES_I18N[lang] || window.PAGES_I18N.ar;
  var rtl = ['ar','ur','fa','ku','ps','he'].indexOf(lang) !== -1;
  document.documentElement.lang = lang;
  document.documentElement.dir = rtl ? 'rtl' : 'ltr';
  document.querySelectorAll('[data-i18n]').forEach(function(el){
    var k = el.getAttribute('data-i18n');
    if(t[k]) el.textContent = t[k];
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(function(el){
    var k = el.getAttribute('data-i18n-ph');
    if(t[k]) el.placeholder = t[k];
  });
};

// ═══ Language Switcher ═══
window.PAGES_I18N.injectSwitcher = function(){
  if(document.getElementById('globalLangSelect')) return;
  var bar = document.querySelector('.lang-bar');
  if(!bar){
    bar = document.createElement('div');
    bar.className = 'lang-bar';
    document.body.appendChild(bar);
  }
  var langs = {
    ar:'🇸🇦 العربية', en:'🇬🇧 English', fr:'🇫🇷 Français',
    es:'🇪🇸 Español', de:'🇩🇪 Deutsch', tr:'🇹🇷 Türkçe',
    ur:'🇵🇰 اردو', id:'🇮🇩 Indonesia', ru:'🇷🇺 Русский',
    zh:'🇨🇳 中文', hi:'🇮🇳 हिन्दी', fa:'🇮🇷 فارسی',
    bn:'🇧🇩 বাংলা', pt:'🇵🇹 Português'
  };
  var sel = document.createElement('select');
  sel.id = 'globalLangSelect';
  sel.className = 'lang-select';
  Object.keys(langs).forEach(function(code){
    var opt = document.createElement('option');
    opt.value = code;
    opt.textContent = langs[code];
    sel.appendChild(opt);
  });
  sel.value = localStorage.getItem('lang') || 'ar';
  sel.addEventListener('change', function(){
    localStorage.setItem('lang', this.value);
    window.PAGES_I18N.apply();
  });
  // ضعها قبل زر الرئيسية
  var firstA = bar.querySelector('a');
  if(firstA) bar.insertBefore(sel, firstA);
  else bar.appendChild(sel);
};

