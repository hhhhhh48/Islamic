// ═══ دالة تطبيق الترجمة على صفحة ═══
window.applyPagesI18n = function() {
  var lang = localStorage.getItem('lang') || (function(){
    var n = (navigator.language || 'en').split('-')[0].toLowerCase();
    return window.PAGES_I18N[n] ? n : 'ar';
  })();
  var dict = window.PAGES_I18N[lang] || window.PAGES_I18N.ar;
  var rtl = ['ar','ur','fa','ku','ps'].indexOf(lang) !== -1;

  document.documentElement.lang = lang;
  document.documentElement.dir = rtl ? 'rtl' : 'ltr';

  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    var key = el.getAttribute('data-i18n');
    if (dict[key]) el.textContent = dict[key];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(function(el) {
    var key = el.getAttribute('data-i18n-placeholder');
    if (dict[key]) el.placeholder = dict[key];
  });

  // فتح التبويب النشط حسب اللغة إن وُجد
  if (window.__refreshTabs) window.__refreshTabs();
};

// ═══ إنشاء زر تبديل اللغة ═══
window.injectLangSelector = function() {
  var langNames = {
    ar:'🇸🇦 العربية', en:'🇬🇧 English', fr:'🇫🇷 Français', es:'🇪🇸 Español',
    de:'🇩🇪 Deutsch', tr:'🇹🇷 Türkçe', ur:'🇵🇰 اردو', id:'🇮🇩 Indonesia',
    ru:'🇷🇺 Русский', zh:'🇨🇳 中文', hi:'🇮🇳 हिन्दी', fa:'🇮🇷 فارسی'
  };
  var wrap = document.querySelector('.lang-bar');
  if (!wrap) {
    wrap = document.createElement('div');
    wrap.className = 'lang-bar';
    document.body.appendChild(wrap);
  }
  var sel = document.createElement('select');
  sel.className = 'lang-select';
  sel.id = 'pagesLangSelect';
  Object.entries(langNames).forEach(function(kv) {
    var opt = document.createElement('option');
    opt.value = kv[0];
    opt.textContent = kv[1];
    sel.appendChild(opt);
  });
  sel.value = localStorage.getItem('lang') || 'ar';
  sel.addEventListener('change', function(e) {
    localStorage.setItem('lang', e.target.value);
    window.applyPagesI18n();
  });
  // ضع select قبل زر "الرئيسية" إن وُجد
  var firstChild = wrap.firstChild;
  if (firstChild) wrap.insertBefore(sel, firstChild);
  else wrap.appendChild(sel);
};

// ═══ حماية: تخطى الرئيسية (عندها i18n الخاص بها) ═══
(function(){
  if (document.getElementById('langSelect')) return; // الرئيسية
  // الصفحات الفرعية فقط
  document.addEventListener('DOMContentLoaded', function(){
    if (typeof window.injectLangSelector === 'function') {
      var existing = document.getElementById('pagesLangSelect');
      if (!existing) window.injectLangSelector();
      if (typeof window.applyPagesI18n === 'function') window.applyPagesI18n();
    }
  });
})();
