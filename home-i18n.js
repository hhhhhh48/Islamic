// ═══ Apply function ═══
window.applyHomeI18n = function(){
  var lang = localStorage.getItem('lang') || 'ar';
  if (!window.HOME_I18N[lang]) lang = 'ar';
  var t = window.HOME_I18N[lang];
  var rtl = ['ar','ur','fa','ku','ps','he'].indexOf(lang) !== -1;
  document.documentElement.lang = lang;
  document.documentElement.dir = rtl ? 'rtl' : 'ltr';

  document.querySelectorAll('[data-h]').forEach(function(el){
    var k = el.getAttribute('data-h');
    if (t[k]) el.innerHTML = t[k];
  });
  document.querySelectorAll('[data-h-attr]').forEach(function(el){
    var k = el.getAttribute('data-h-attr');
    var attr = el.getAttribute('data-h-target');
    if (t[k] && attr) el.setAttribute(attr, t[k]);
  });
};
