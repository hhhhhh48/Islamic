window.applyAlgeriaI18n = function(){
  var lang = localStorage.getItem('lang') || 'ar';
  if(lang !== 'ar' && lang !== 'en') lang = 'ar';
  var t = window.ALGERIA_I18N[lang];
  var rtl = lang === 'ar';
  document.documentElement.lang = lang;
  document.documentElement.dir = rtl ? 'rtl' : 'ltr';
  document.querySelectorAll('[data-ai18n]').forEach(function(el){
    var k = el.getAttribute('data-ai18n');
    if(t[k]) el.innerHTML = t[k];
  });
};
